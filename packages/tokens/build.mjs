// Generates dist/tokens.css, dist/tokens.ts and the Android HeyTokens.kt from hey.tokens.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(join(here, 'hey.tokens.json'), 'utf8'));
const ktPath = join(here, '../../android/src/main/kotlin/ai/hey/designsystem/token/HeyTokens.kt');

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith('$'));
const val = (o) => o.$value;
const num = (n) => String(n);

// ---------- CSS ----------
const colorVars = (theme) =>
  entries(src.color[theme]).map(([k, v]) => `  --hey-color-${k}: ${val(v)};`).join('\n');

const fixedVars = [];
for (const [k, v] of entries(src.space)) fixedVars.push(`  --hey-space-${k}: ${val(v)}px;`);
for (const [k, v] of entries(src.radius)) fixedVars.push(`  --hey-radius-${k}: ${val(v)}px;`);
for (const [k, v] of entries(src['border-width'])) fixedVars.push(`  --hey-border-${k}: ${val(v)}px;`);
fixedVars.push(`  --hey-font-family: ${val(src.font.family)}, ${val(src.font['family-fallback'])};`);
for (const [k, t] of entries(src.type.web)) {
  fixedVars.push(`  --hey-type-${k}-size: ${t.size}px;`);
  fixedVars.push(`  --hey-type-${k}-line: ${t.lineHeight}px;`);
  fixedVars.push(`  --hey-type-${k}-weight: ${t.weight};`);
  fixedVars.push(`  --hey-type-${k}-tracking: ${t.tracking}em;`);
}
for (const [k, v] of entries(src.size)) fixedVars.push(`  --hey-size-${k}: ${val(v)}px;`);
for (const [k, v] of entries(src.sheet)) fixedVars.push(`  --hey-sheet-${k}: ${val(v)}px;`);
for (const [k, v] of entries(src.motion)) {
  const x = val(v);
  fixedVars.push(Array.isArray(x)
    ? `  --hey-motion-${k}: cubic-bezier(${x.join(', ')});`
    : `  --hey-motion-${k}: ${x}ms;`);
}
for (const [k, v] of entries(src.elevation)) fixedVars.push(`  --hey-elevation-${k}: ${val(v)};`);

const css = `/* GENERATED by packages/tokens/build.mjs — do not edit */
@font-face {
  font-family: "Pretendard";
  src: url("../fonts/PretendardVariable.woff2") format("woff2-variations");
  font-weight: 45 920;
  font-style: normal;
  font-display: swap;
}

:root {
${fixedVars.join('\n')}
}

:root,
[data-theme="light"] {
${colorVars('light')}
  color-scheme: light;
}

[data-theme="dark"] {
${colorVars('dark')}
  color-scheme: dark;
}

html,
body {
  min-height: 100%;
}

/* 앱 루트(#root)와 Storybook 루트는 세로 flex 열이다: 틀이 남는 높이를 채워 고정 막대가 화면 아래에 붙는다. */
#root,
#storybook-root {
  display: flex;
  flex-direction: column;
  min-height: 100%;
}

html,
body {
  height: 100%;
}

*,
*::before,
*::after {
  box-sizing: border-box;
}

body {
  margin: 0;
  font-family: var(--hey-font-family);
  font-size: var(--hey-type-body-size);
  line-height: var(--hey-type-body-line);
  font-weight: var(--hey-type-body-weight);
  background: var(--hey-color-bg-page);
  color: var(--hey-color-fg-default);
}
`;

// ---------- TS ----------
const colorObj = (theme) =>
  Object.fromEntries(entries(src.color[theme]).map(([k, v]) => [camel(k), val(v)]));
const typeObj = (g) =>
  Object.fromEntries(entries(src.type[g]).map(([k, t]) => [camel(k), { size: t.size, lineHeight: t.lineHeight, weight: t.weight, tracking: t.tracking }]));
const plain = (g) => Object.fromEntries(entries(src[g]).map(([k, v]) => [camel(k.match(/^\d/) ? `s${k}` : k), val(v)]));

const tokens = {
  color: { light: colorObj('light'), dark: colorObj('dark') },
  space: plain('space'),
  radius: plain('radius'),
  border: plain('border-width'),
  fontFamily: `${val(src.font.family)}, ${val(src.font['family-fallback'])}`,
  type: { web: typeObj('web'), car: typeObj('car') },
  size: plain('size'),
  sheet: plain('sheet'),
  motion: plain('motion'),
  elevation: plain('elevation'),
};
const ts = `// GENERATED by packages/tokens/build.mjs — do not edit
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

export type HeyTokens = typeof tokens;
export type ThemeName = 'light' | 'dark';
export type ColorToken = keyof HeyTokens['color']['light'];
`;

// ---------- Kotlin ----------
const ktColor = (hex) => {
  let h = hex.replace('#', '').toUpperCase();
  const rgb = h.slice(0, 6);
  const a = h.length === 8 ? h.slice(6, 8) : 'FF';
  return `Color(0x${a}${rgb})`;
};
const dp = (g) => entries(src[g]).map(([k, v]) => `    val ${camel(k.match(/^\d/) ? `s${k}` : k)} = ${val(v)}.dp`).join('\n');
const colorKeys = entries(src.color.light).map(([k]) => camel(k));
const colorBlock = (theme, name) =>
  `val ${name} = HeyColors(\n${entries(src.color[theme]).map(([k, v]) => `    ${camel(k)} = ${ktColor(val(v))}`).join(',\n')},\n)`;
const carType = entries(src.type.car)
  .map(([k, t]) => `    val ${camel(k)} = HeyTypeSpec(${t.size}.sp, ${t.lineHeight}.sp, ${t.weight}, ${t.tracking}f)`).join('\n');
const motionKt = entries(src.motion).map(([k, v]) => {
  const x = val(v);
  return Array.isArray(x)
    ? `    val ${camel(k)} = floatArrayOf(${x.map((n) => `${n}f`).join(', ')})`
    : `    const val ${camel(k)} = ${x}`;
}).join('\n');

const kt = `// GENERATED by packages/tokens/build.mjs — do not edit
package ai.hey.designsystem.token

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

object HeyTokens {
  object Space {
${dp('space')}
  }
  object Radius {
${dp('radius')}
  }
  object Border {
${dp('border-width')}
  }
  object Size {
${dp('size')}
  }
  object Sheet {
${dp('sheet')}
  }
  object Motion {
${motionKt}
  }
  object CarType {
${carType}
  }
}

data class HeyTypeSpec(val size: TextUnit, val lineHeight: TextUnit, val weight: Int, val trackingEm: Float)

data class HeyColors(
${colorKeys.map((k) => `    val ${k}: Color`).join(',\n')},
)

${colorBlock('light', 'HeyLightColors')}

${colorBlock('dark', 'HeyDarkColors')}
`;

mkdirSync(join(here, 'dist'), { recursive: true });
mkdirSync(dirname(ktPath), { recursive: true });
writeFileSync(join(here, 'dist/tokens.css'), css);
writeFileSync(join(here, 'dist/tokens.ts'), ts);
writeFileSync(ktPath, kt);
console.log('tokens: wrote dist/tokens.css, dist/tokens.ts, HeyTokens.kt');
